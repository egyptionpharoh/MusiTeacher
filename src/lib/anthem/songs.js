export const PENDING = [];

const cache = new Map();
/** النموذج الموسيقي للأغنية (والنسخة المنقولة إن طُلبت) */
export function getSong(id, altKey) {
  const k = id + '|' + (altKey || ''); if (cache.has(k)) return cache.get(k);
  const meta = SONGS.find((s) => s.id === id); if (!meta) return null;
  let song = parseSong(SCORES[id]);
  if (altKey) { const a = (meta.alt || []).find((x) => x.key === altKey); if (a) song = transposeSong(song, a.key, a.steps, a.semis); }
  const res = { ...meta, music: song };
  cache.set(k, res); return res;
}
/** وصف السلم أو المقام: اسمه إن كان مطبوعًا أو معروفًا (المقامات)، وإلا وصف الدليل */
export const keyText = (s, music = s.music) => (MAQAMAT[music.key] || s.source.printed.includes('السلم مطبوع') ? keyLabel(music.key) : keySigLabel(music.key));
/** القيم المعروضة في قائمة المراجعة الداخلية */
export function reviewRow(id) {
  const s = getSong(id); const m = s.music;
  return { id, title: s.title, measures: m.measures.length, clef: s.clef, key: m.key, keyText: keyText(s), time: m.time, voices: s.voices, source: `${s.source.file} — ${s.source.pages}`, rights: RIGHTS[s.rights].label, review: REVIEW[s.review.status].label, notes: s.review.notes };
}
/** السرعة الافتراضية: من الأصل إن وُجدت، وإلا اقتراح تعليمي معلن */
export function defaultTempo(song) {
  if (song.music.tempo) return { bpm: song.music.tempo, fromSource: true };
  const t = song.music.time; return { bpm: t === '6/8' ? 108 : t === '4/4' ? 100 : 96, fromSource: false };
}
