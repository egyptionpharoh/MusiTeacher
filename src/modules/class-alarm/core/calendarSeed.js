function guideItem(n, title, category, spec, extra) {
  const base = { seedId: `guide-${String(n).padStart(2, '0')}`, title, category, ...extra };
  delete base.dateText;
  let kind = 'annual', annual = null, rule = '', hijri = null, dateText = extra.dateText || '', review = { need: false, note: '' };
  if (typeof spec === 'string') { const [m, d] = spec.split('/').map(Number); annual = { m, d }; dateText = dateText || spec; }
  else if (spec.month) { annual = { m: spec.month, d: 1, month: true }; dateText = `شهر ${MONTH_AR[spec.month - 1]}`; }
  else if (spec.range) { const [m, d, m2, d2] = spec.range; annual = { m, d, m2, d2 }; dateText = m === m2 ? `${d}-${d2}/${m}` : `${m}/${d} - ${m2}/${d2}`; }
  else if (spec.hijri) {
    kind = 'variable'; const [m, d, d2] = spec.hijri; hijri = { m, d, d2: d2 || 0 }; rule = spec.rule; dateText = spec.rule;
    review = { need: true, note: 'مناسبة هجرية: التاريخ المقترح تقريبي (تقويم أم القرى) ويُعتمد بعد إعلان الرؤية في السلطنة. حدّد التاريخ لهذا العام.' };
  } else if (spec.rule) {
    kind = 'variable'; rule = spec.rule; dateText = spec.rule;
    review = { need: true, note: `ورد توقيتها في الدليل «${spec.rule}» دون يوم محدد. حدّد تاريخ هذا العام.` };
  }
  return { ...base, kind, annual, rule, hijri, review: extra.review || review, src: { ...GUIDE, ref: `م ${n} – تاريخ المناسبة في الدليل: «${dateText}»` } };
}

