const byId = new Map(PHRASES.map((p) => [p.id, p]));
export const phraseById = (id) => byId.get(id) || null;

/** نص العبارة بالصيغة المناسبة؛ custom يتقدم دائمًا (يكتبه المعلم بنفسه). */
export function phraseText({ phraseId, custom, gender }) {
  const c = typeof custom === 'string' ? custom.trim() : '';
  if (c) return c.slice(0, 160);
  const p = byId.get(phraseId) || PHRASES[0];
  return gender === 'f' ? p.f : p.m;
}

export const phrasesFor = (tag) => (!tag || tag === 'all' ? PHRASES : PHRASES.filter((p) => p.tag === tag));

