const STEP = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
// 'E½b3' → midi (يدعم b و # و ½b)
export function m(n) {
  const r = /^([A-G])(½b|½#|b|#)?(\d)$/.exec(n); if (!r) throw new Error('bad note ' + n);
  const acc = { 'b': -1, '#': 1, '½b': -0.5, '½#': 0.5 }[r[2]] || 0;
  return 12 * (+r[3] + 1) + STEP[r[1]] + acc;
}
function seq(list, defBeats = 1, opt = {}) {
  // list: "C3 D3:2 E½b3 F3:0.5~" ← نغمة[:ضربات][~]   (~ = حلية موصولة: تُعزف باليد اليسرى وحدها دون ضربة ريشة)
  // الوتر والإصبع ووضع اليد يختارها «محرّك المواضع» للجملة كلها (لا لكل نغمة منفردة).
  // R[:ضربات] = سكتة (يتقدّم الزمن دون نغمة؛ الريشة تبدأ بعدها نازلة).
  const raw = []; let t0 = 0;
  for (let tok of list.trim().split(/\s+/)) {
    if (tok === '|') continue;
    if (tok === 'R' || tok.startsWith('R:')) { const b = tok.includes(':') ? +tok.split(':')[1] : defBeats; t0 += b; if (raw.length) raw[raw.length - 1].restAfter = true; continue; }
    const slur = tok.endsWith('~'); if (slur) tok = tok.slice(0, -1);
    const [n, b] = tok.split(':'), beats = b ? +b : defBeats; raw.push({ midi: m(n), beats, slur, start: t0 }); t0 += beats;
  }
  const path = planPositions(raw, opt);
  const evs = []; let dir = 'down';
  raw.forEach((r, i) => {
    const longN = r.beats >= 2, risha = r.slur ? null : (longN ? 'down' : dir);
    evs.push({ midi: r.midi, beats: r.beats, start: r.start, risha, slur: r.slur, ...path[i] });
    if (!r.slur) dir = longN || r.restAfter ? 'down' : (risha === 'down' ? 'up' : 'down');
  });
  return evs;
}
/**
 * مقطوعة مدوّنة مازورةً مازورة كما في النوتة. bars: { اسم: 'نغمات المازورة' } ، order: ترتيب العزف (مع الإعادات والقفلات).
 * يتحقق من أن مجموع أزمنة كل مازورة يساوي الميزان (meter بالنوار) — فأي خطأ في النقل يُكشف عند التحميل. الأسماء المبدوءة بـ ^ أناكروز.
 */
export function piece(meter, bars, order) {
  const len = (str) => str.trim().split(/\s+/).reduce((a, tok) => a + (tok.includes(':') ? +tok.replace('~', '').split(':')[1] : 1), 0);
  for (const [k, v] of Object.entries(bars)) if (!k.startsWith('^') && Math.abs(len(v) - meter) > 1e-9) throw new Error(`مازورة «${k}» مجموعها ${len(v)} لا ${meter}`);
  return order.trim().split(/\s+/).map((k) => { if (!(k in bars)) throw new Error('مازورة غير معرّفة: ' + k); return bars[k]; }).join(' | ');
}
