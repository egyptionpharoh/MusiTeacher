/** نوع الضربة عند موضع على الرقمة (rho = البعد عن المركز ÷ نصف القطر) */
export function strokeAt(inst, rho) { const z = inst.zones.find((q) => rho >= q.r[0] && rho < q.r[1]); return z ? z.stroke : inst.zones[inst.zones.length - 1].stroke; }
