export const NOTE_AR = ['دو', 'دو♯', 'ري', 'ري♯', 'مي', 'فا', 'فا♯', 'صول', 'صول♯', 'لا', 'لا♯', 'سي'];
export const NOTE_AR_FLAT = ['دو', 'ري♭', 'ري', 'مي♭', 'مي', 'فا', 'صول♭', 'صول', 'لا♭', 'لا', 'سي♭', 'سي'];
export const NOTE_EN = ['C', 'C♯', 'D', 'D♯', 'E', 'F', 'F♯', 'G', 'G♯', 'A', 'A♯', 'B'];
const BLACK = new Set([1, 3, 6, 8, 10]);
export const pc = (midi) => ((midi % 12) + 12) % 12;
export const isBlack = (midi) => BLACK.has(pc(midi));
export const octave = (midi) => Math.floor(midi / 12) - 1;              // دو الوسطى (60) = دو٤
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
export const arNum = (n) => String(n).replace(/\d/g, (d) => AR_DIGITS[d]);
/** اسم النغمة: lang = 'ar' (دو ري مي…) أو 'en' (C D E…)؛ withOct يضيف رقم الطبقة (دو٤ / C4) */
export function noteName(midi, lang = 'ar', withOct = false) {
  const p = pc(midi);
  if (lang === 'en') return NOTE_EN[p] + (withOct ? octave(midi) : '');
  return NOTE_AR[p] + (withOct ? arNum(octave(midi)) : '');
}
export const freqOf = (midi) => 440 * Math.pow(2, (midi - 69) / 12);

// ---------- المفاتيح: 61 مفتاحًا، 36 أبيض و25 أسود ----------
export const LOW = 36, HIGH = 96, MIDDLE_C = 60;
export const KEYS = (() => {
  const keys = []; let wi = 0;
  for (let m = LOW; m <= HIGH; m++) {
    const black = isBlack(m);
    // المفتاح الأبيض يأخذ خانة كاملة، والأسود يقع على الحد بين الأبيضين المجاورين (ثم يُزاح قليلًا كما في البيانو الحقيقي)
    if (!black) keys.push({ id: 'k' + m, midi: m, black: false, slot: wi++ });
    else keys.push({ id: 'k' + m, midi: m, black: true, slot: wi - 0.5 });
  }
  return keys;
})();
export const WHITE_COUNT = KEYS.filter((k) => !k.black).length;           // 36
export const keyByMidi = Object.fromEntries(KEYS.map((k) => [k.midi, k]));
export const keyById = Object.fromEntries(KEYS.map((k) => [k.id, k]));
