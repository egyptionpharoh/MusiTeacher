// ---------------------------------------------------------------------
//  تحليل المدوّنة إلى موازير وعلامات وضربات
// ---------------------------------------------------------------------
export function unitsPerBeat(meter) { return meter[1] === 8 ? 6 : 4; }
export function unitsPerBar(meter) { return meter[1] === 8 ? meter[0] * 2 : meter[0] * 4; }
export function beatsPerBar(meter) { return unitsPerBar(meter) / unitsPerBeat(meter); }

/** يعيد { bars: [[{k:'D'|'T'|'R', d, acc, tie, tied, beam, u}]], hits: [{u, k, acc}], total } — u موضع البداية بالدوبل كروش من أول المدوّنة */
export function parsePattern(p, meter) {
  const upbar = unitsPerBar(meter);
  let u = 0, beamId = 0, inBeam = 0, tiedNext = false;
  const hits = [];
  const bars = p.split('|').map((barStr, bi) => {
    const notes = [];
    for (let tok of barStr.trim().split(/\s+/)) {
      if (!tok) continue;
      if (tok[0] === '[') { inBeam = ++beamId; tok = tok.slice(1); }
      let close = false;
      if (tok.endsWith(']')) { close = true; tok = tok.slice(0, -1); }
      const m = /^([DTR])(\d+)(>?)(~?)$/.exec(tok);
      if (!m) throw new Error(`علامة غير مفهومة: ${tok}`);
      const n = { k: m[1], d: +m[2], acc: !!m[3], tie: !!m[4], tied: tiedNext, beam: inBeam, u, bar: bi };
      if (n.k !== 'R' && !n.tied) hits.push({ u, k: n.k, acc: n.acc });
      tiedNext = n.tie; u += n.d; notes.push(n);
      if (close) inBeam = 0;
    }
    const len = notes.reduce((s, n) => s + n.d, 0);
    if (len !== upbar) throw new Error(`مازورة ${bi + 1} طولها ${len} والمطلوب ${upbar}: ${barStr}`);
    return notes;
  });
  return { bars, hits, total: u };
}

export function buildArt(a) {
  const tracks = a.tracks.map((t, i) => ({ ...t, i, ...parsePattern(t.p, a.meter), info: INSTRUMENTS[t.inst] }));
  const total = tracks[0].total;
  for (const t of tracks) if (t.total !== total) throw new Error(`${a.id}: أطوال المسارات مختلفة`);
  return { ...a, tracks, total, upb: unitsPerBeat(a.meter), upbar: unitsPerBar(a.meter), barsN: total / unitsPerBar(a.meter) };
}
