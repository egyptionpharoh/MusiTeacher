const IV = { 0.5: 'ربع درجة', 1: 'نصف درجة', 1.5: 'ثلاثة أرباع الدرجة', 2: 'درجة كاملة', 2.5: 'درجة وربع', 3: 'درجة ونصف', 3.5: 'درجة وثلاثة أرباع', 4: 'درجتان', 4.5: 'درجتان وربع', 5: 'درجتان ونصف' };
export const intervalAr = (s) => IV[s] || '';

export function fingerFor(s) { return s === 0 ? 0 : s <= 2 ? 1 : s <= 3.5 ? 2 : s <= 4 ? 3 : 4; }
/** موضع نغمة في الوضع الأول: أقرب وتر يعطيها بأقل مسافة من الأنف (الوتر المطلق أولًا) */
export function placeNote(midi) {
  let best = null;
  for (const c of COURSES) {
    if (c.index === 0) continue;                                   // القرار للنغمات الأخفض من يكاه فقط
    const s = Math.round((midi - c.midi) * 2) / 2;
    if (s >= 0 && s <= 5 && (!best || s < best.semis)) best = { course: c.index, semis: s };
  }
  if (!best) { const s = Math.round((midi - 36) * 2) / 2; if (s >= 0 && s <= 5) best = { course: 0, semis: s }; }
  if (!best) return null;
  return { ...best, finger: fingerFor(best.semis) };
}
export const midiOf = (course, semis) => COURSES[course].midi + semis;
export const freqOf = (midi) => 440 * Math.pow(2, (midi - 69) / 12);

